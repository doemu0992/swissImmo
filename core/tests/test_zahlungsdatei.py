class ZahllaufAblehnungTests(TestCase):
    """Der Zahllauf lehnt unvollständige Kreditoren VOR der Dateierzeugung ab."""

    def setUp(self):
        from finance.booking import ensure_kontenplan
        _test_organisation(firma='V AG', iban=VW_IBAN, strasse='Bahnhofstrasse 12',
                           plz='8001', ort='Zürich')
        ensure_kontenplan()
        self.lg, *_ = _basis_objekte()
        self.c = Client()
        self.c.force_login(_team_user('Verwaltung'))

    def _datei(self, *rechnungen):
        return self.c.post('/neu/zahllauf/', {
            'aktion': 'datei', 'rechnung_ids': [str(r.id) for r in rechnungen],
            'ausfuehrungsdatum': '2026-10-30'})

    def test_vollstaendiger_lauf_erzeugt_die_datei_mit_beiden_anschriften(self):
        a = _freigegeben(self.lg)
        r = self._datei(a)
        self.assertEqual(r.status_code, 200)
        self.assertEqual(r['Content-Type'], 'application/xml')
        ok, fehler, doc = gueltig(r.content)
        self.assertTrue(ok, fehler)
        self.assertEqual(doc.xpath('//p:Dbtr/p:PstlAdr/p:StrtNm/text()', namespaces=NS), ['Bahnhofstrasse'])
        self.assertEqual(doc.xpath('//p:Dbtr/p:PstlAdr/p:BldgNb/text()', namespaces=NS), ['12'])
        self.assertEqual(doc.xpath('//p:Cdtr/p:PstlAdr/p:TwnNm/text()', namespaces=NS), ['Zürich'])
        a.refresh_from_db()
        self.assertEqual(a.status, 'in_zahlung')

    def test_kreditoren_ohne_anschrift_werden_je_kreditor_gemeldet_und_nichts_wird_gebucht(self):
        gut = _freigegeben(self.lg, 'Gut AG')
        ohne1 = _freigegeben(self.lg, 'Erste ohne AG', ort='')
        ohne2 = _freigegeben(self.lg, 'Zweite ohne AG', ort='')
        r = self._datei(gut, ohne1, ohne2)
        self.assertEqual(r.status_code, 302)                       # keine Datei
        for k in (gut, ohne1, ohne2):
            k.refresh_from_db()
            self.assertEqual(k.status, 'freigegeben')              # auch die gute: kein Teillauf
            self.assertIsNone(k.zahlung_ausfuehrung)
        seite = self.c.get('/neu/zahllauf/')
        self.assertEqual(seite.status_code, 200)
        liste = seite.context['fehler_liste']
        self.assertEqual([f['lieferant'] for f in liste], ['Erste ohne AG', 'Zweite ohne AG'])
        inhalt = seite.content.decode()
        self.assertIn(f'/neu/kreditoren/{ohne1.id}/adresse/', inhalt)
        self.assertIn(f'/neu/kreditoren/{ohne2.id}/adresse/', inhalt)
        self.assertIn('Zahlungsdatei wurde nicht erzeugt', inhalt)
        # Die Liste steht einmal da, nicht bei jedem späteren Aufruf
        self.assertEqual(self.c.get('/neu/zahllauf/').context['fehler_liste'], [])

    def test_vorschlag_zeigt_die_beanstandung_schon_vor_dem_klick(self):
        ohne = _freigegeben(self.lg, 'Ohne AG', ort='')
