class ReferenzartMatrixTests(SimpleTestCase):
    """QRR nur mit QR-IBAN, bei QR-IBAN nur QRR — nie umgekehrt (FIN-08, FIN-11)."""

    def _remit(self, r):
        xml, _, _ = erzeuge([r])
        ok, fehler, doc = gueltig(xml)
        self.assertTrue(ok, fehler)
        return doc.xpath('//p:CdtTrfTxInf/p:RmtInf', namespaces=NS)[0]

    def test_qr_iban_mit_gueltiger_qrr_ergibt_strukturierte_referenz(self):
        for iban in (QR_IBAN, QR_IBAN_2):
            with self.subTest(iban=iban):
                rmt = self._remit(rechnung(iban=iban, referenz='21 00000 00003 13947 14300 09017'))
                self.assertEqual(rmt.xpath('p:Strd/p:CdtrRefInf/p:Tp/p:CdOrPrtry/p:Prtry/text()', namespaces=NS), ['QRR'])
                self.assertEqual(rmt.xpath('p:Strd/p:CdtrRefInf/p:Ref/text()', namespaces=NS), [QRR])
                self.assertEqual(rmt.xpath('p:Ustrd', namespaces=NS), [])

    def test_normale_iban_bekommt_nie_qrr_sondern_freitext(self):
        for referenz, erwartet in ((QRR, QRR), ('Rechnung 17', 'Rechnung 17'),
                                   ('', 'Rechnung Müller & Söhne AG'),
                                   ('RF18539007547034', 'RF18539007547034')):
            with self.subTest(referenz=referenz):
                rmt = self._remit(rechnung(iban=IBAN, referenz=referenz))
                self.assertEqual(rmt.xpath('p:Strd', namespaces=NS), [])
                self.assertNotIn('QRR', etree.tostring(rmt).decode())
                self.assertEqual(rmt.xpath('p:Ustrd/text()', namespaces=NS), [erwartet])

    def test_qr_iban_ohne_gueltige_referenz_wird_abgelehnt_statt_ustrd(self):
        for referenz in ('', 'Rechnung 17', 'RF18539007547034', QRR[:-1] + '8', QRR[:-1], QRR + '0'):
            with self.subTest(referenz=referenz):
                with self.assertRaises(ZahlungsdateiFehler) as ctx:
                    erzeuge([rechnung(7, iban=QR_IBAN, referenz=referenz)])
                p = ctx.exception.probleme[0]
                self.assertEqual(p.rechnung_id, 7)
                self.assertIn('referenz', p.codes)

    def test_nicht_zahlbare_zahlungen_erzeugen_keine_teildatei(self):
        gut = rechnung(1)
        for was, schlecht, code in (
                ('ungültige IBAN', rechnung(2, iban='CH0000000000000000000'), 'iban'),
                ('keine IBAN', rechnung(3, iban=''), 'iban'),
                ('Betrag 0', rechnung(4, betrag='0.00'), 'betrag'),
                ('Betrag zu gross', rechnung(5, betrag='1000000000.00'), 'betrag'),
                ('ohne Namen', rechnung(6, lieferant='  '), 'name'),
                ('ohne Ort', rechnung(7, ort=''), 'adresse'),
                ('ohne Land', rechnung(8, land=''), 'adresse'),
                ('Land dreistellig', rechnung(9, land='CHE'), 'adresse'),
                ('Land klein', rechnung(10, land='ch'), None)):
            with self.subTest(was=was):
                if code is None:      # Kleinschreibung wird akzeptiert und gross geschrieben
                    xml, n, _ = erzeuge([gut, schlecht])
                    self.assertIn('<Ctry>CH</Ctry>', xml.decode())
                    continue
                with self.assertRaises(ZahlungsdateiFehler) as ctx:
                    erzeuge([gut, schlecht])
                self.assertEqual([p.rechnung_id for p in ctx.exception.probleme], [schlecht.id])
                self.assertIn(code, ctx.exception.probleme[0].codes)

    def test_jeder_fehlerhafte_kreditor_steht_in_der_meldung(self):
        rs = [rechnung(1), rechnung(2, ort=''), rechnung(3, lieferant='Zweite AG', ort=''),
              rechnung(4, iban=QR_IBAN, referenz='')]
        probleme = pruefe_zahlungen(rs, 'Muster AG', VW_IBAN, VW_ADRESSE)
        self.assertEqual([p.rechnung_id for p in probleme], [2, 3, 4])
        self.assertEqual(probleme[1].lieferant, 'Zweite AG')

    def test_auftraggeber_ohne_anschrift_oder_mit_falscher_iban_wird_abgelehnt(self):
        for was, kw in (('ohne Adresse', {'debtor_adresse': {}}),
                        ('ohne Ort', {'debtor_adresse': {**VW_ADRESSE, 'ort': ''}}),
                        ('IBAN falsch', {'debtor_iban': 'CH5604835012345678008'}),
                        ('ohne Name', {'debtor_name': ''})):
            with self.subTest(was=was):
                with self.assertRaises(ZahlungsdateiFehler) as ctx:
                    erzeuge([rechnung(1)], **kw)
                self.assertIsNone(ctx.exception.probleme[0].rechnung_id)

    def test_leere_auswahl_ergibt_keine_datei(self):
        with self.assertRaises(ZahlungsdateiFehler):
            erzeuge([])


