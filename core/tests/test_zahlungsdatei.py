"""Die Zahlungsdatei (pain.001) nach den Swiss Payment Standards 2026.

ANLASS (Etappe 0, 28.10.2026; Befunde FUNK-04, FIN-08, FIN-09, FIN-11)

Ab dem 14.11.2026 verlangen die SPS in der pain.001 die strukturierte
Anschrift von Zahlungspflichtigem und Begünstigtem (mindestens Ort und Land),
und die Referenzart hängt an der IBAN: QR-Referenz nur bei QR-IBAN, bei einer
QR-IBAN nur die QR-Referenz. Bis dahin enthielt die Datei keine Anschrift,
sendete QRR auch zu normalen IBAN, Ustrd zu QR-IBAN und prüfte die IBAN nicht
auf die Prüfsumme.

QUELLEN UND GRENZEN

* Das ISO-Schema liegt im Repo (`core/tests/daten/pain.001.001.09.xsd`, Kopf
  «Generated by Standards Editor … ISO 20022», aus einem Spiegel der
  ISO-Veröffentlichung). Gegen dieses Schema validieren die Tests.
* Die SPS-Regeln stehen im Befund FIN-08 und im SIX-Factsheet zur Anschrift
  (im Auditbericht zitiert). Die SIX-Seiten waren beim Bau dieser Tests nicht
  erreichbar; was NICHT belegt ist (SCOR, ChrgBr, genauer Zeichensatz,
  InitgPty-Anschrift, Ausführungsdatum), ist weder umgesetzt noch getestet und
  steht als Fachpunkt im Bericht.

GEGENPROBEN stehen im Schlussbericht, je Testgruppe.
"""
